NEXT_DAY = "2026-10-10"
PLAN_KEYS = ("brand", "project", "team", "agent", "skills", "tier", "executor", "done_when", "note")


class TestCarry(Base):
    def setUp(self):
        super().setUp()
        self.run_day("collect")
        self.fill_all()
        self.run_day("lock")

    def carry_path(self):
        return os.path.join(self.root, "TSST/daily/carry.json")

    def test_round_trip_keeps_plan_fields(self):
        self.run_day("set", "3", "executor=ahmed", "team=", "agent=", "tier=", "skills=",
                     "done_when=call them", "--owner-ok")
        self.run_day("set", "4", "status=doing", "note=half way")
        self.run_day("set", "1", "status=done")
        before = {r["task"]: r for r in self.board()["rows"] if r["status"] != "done"}
        self.assertEqual(self.run_day("close")[0], 0)
        rc, _, err = self.run_day("collect", today=NEXT_DAY)
        self.assertEqual(rc, 0, err)
        b = self.board()
        self.assertEqual(b["date"], NEXT_DAY)
        restored = [r for r in b["rows"] if r["source"] == "carried from %s" % TODAY]
        self.assertEqual({r["task"] for r in restored}, set(before))
        self.assertEqual([r["id"] for r in b["rows"][:len(restored)]], list(range(1, len(restored) + 1)),
                         "carried rows come first")
        for r in restored:
            self.assertEqual(r["status"], "todo")
            for k in PLAN_KEYS:
                self.assertEqual(r[k], before[r["task"]][k], k)
        self.assertEqual(json.loads(slurp(self.carry_path()))["rows"], [], "carry cleared after collect")
        self.assertTrue(any(r["note"] == "half way" for r in restored))
        for r in b["rows"]:  # freshly collected rows are unplanned; only the restored ones must validate
            if not r["source"].startswith("carried from"):
                self.run_day("drop", str(r["id"]), today=NEXT_DAY)
        rc, _, err = self.run_day("lock", today=NEXT_DAY)
        self.assertEqual(rc, 0, "restored plans pass lock validation: " + err)

    def test_after_refs_remapped_and_dangling_refs_dropped(self):
        rows = self.board()["rows"]
        self.assertGreaterEqual(len(rows), 6)
        t = {r["id"]: r["task"] for r in rows}
        self.run_day("set", "1", "status=done")
        self.run_day("set", "2", "status=dropped")
        self.run_day("set", "5", "after=4,1,2", "--owner-ok")
        self.run_day("close")
        self.run_day("collect", today=NEXT_DAY)
        new = {r["task"]: r for r in self.board()["rows"]}
        # old 3,4,5,... become new 1,2,3,...; refs to done(1)/dropped(2) rows disappear
        self.assertEqual(new[t[3]]["id"], 1)
        self.assertEqual(new[t[4]]["id"], 2)
        self.assertEqual(new[t[5]]["id"], 3)
        self.assertEqual(new[t[5]]["after"], [2])
        self.assertTrue(all(r["after"] == [] for k, r in new.items() if k != t[5]))

    def test_swapped_row_in_inbox_and_carry(self):
        victim = self.board()["rows"][0]
        self.assertEqual(self.run_day("add", "urgent client call", "executor=ahmed", "done_when=called",
                                      "--owner-ok", "--swap", "1")[0], 0)
        self.run_day("close")
        self.assertIn(victim["task"] + " (swapped out %s)" % TODAY, self.inbox())
        sw = [c for c in json.loads(slurp(self.carry_path()))["rows"] if c["task"] == victim["task"]]
        self.assertEqual(len(sw), 1)
        for k in PLAN_KEYS[:-1]:
            self.assertEqual(sw[0][k], victim[k], k)
        self.run_day("collect", today=NEXT_DAY)
        same = [r for r in self.board()["rows"] if day.SUFFIX_RE.sub("", r["task"]) == victim["task"]]
        self.assertEqual(len(same), 1, "swapped row not duplicated by inbox + carry")
        self.assertEqual(same[0]["executor"], victim["executor"])
        self.assertNotIn("swapped out", self.inbox(), "inbox cleared by collect")

    def test_crash_between_board_write_and_carry_clear_no_duplicates(self):
        self.run_day("close")
        saved = slurp(self.carry_path())
        self.run_day("collect", today=NEXT_DAY)
        tasks = sorted(r["task"] for r in self.board()["rows"])
        with open(self.carry_path(), "w", encoding="utf-8") as f:  # simulate: carry never cleared
            f.write(saved)
        rc, _, err = self.run_day("collect", "--force", today=NEXT_DAY)
        self.assertEqual(rc, 0, err)
        self.assertEqual(sorted(r["task"] for r in self.board()["rows"]), tasks)
        carried = [r for r in self.board()["rows"] if r["source"].startswith("carried")]
        self.assertTrue(carried and all(r["executor"] and r["done_when"] for r in carried))
        # normal case: carry already cleared; --force must still keep the carried plans
        rc, _, err = self.run_day("collect", "--force", today=NEXT_DAY)
        self.assertEqual(rc, 0, err)
        self.assertEqual(sorted(r["task"] for r in self.board()["rows"]), tasks)
        carried = [r for r in self.board()["rows"] if r["source"] == "carried from %s" % TODAY]
        self.assertTrue(carried and all(r["executor"] and r["done_when"] for r in carried))


class TestRender(Base):
    def test_dropped_rows_hidden_in_render_and_counts(self):
        self.run_day("collect")
        total = len(self.board()["rows"])
        self.fill_all()
        self.run_day("set", "1", "status=dropped", "executor=")
        self.run_day("set", "2", "status=dropped", "executor=")
        md = slurp(os.path.join(self.root, "TSST/daily/today.md"))
        table = [ln for ln in md.splitlines() if ln.startswith("| ") and not ln.startswith("| # ")]
        self.assertEqual(len(table), total - 2)
        self.assertFalse(any(ln.startswith(("| 1 |", "| 2 |")) for ln in table))
        self.assertIn("غير محدد: 0", md)
        self.assertIn("صفوف الفريق: %d" % (total - 2), md)

    def test_show_hides_dropped_and_render_flag_is_state_neutral(self):
        self.run_day("collect")
        total = len(self.board()["rows"])
        self.run_day("drop", "1")
        bpath = os.path.join(self.root, "TSST/daily/board.json")
        before = slurp(bpath)
        os.remove(os.path.join(self.root, "TSST/daily/today.md"))
        rc, out, _ = self.run_day("show", "--render")
        self.assertEqual(rc, 0)
        self.assertIn("dropped: 1", out)
        self.assertIn("rows=%d" % (total - 1), out)
        self.assertNotIn("   1 [", out)
        self.assertEqual(slurp(bpath), before)
        self.assertTrue(os.path.isfile(os.path.join(self.root, "TSST/daily/today.md")))


