def slurp(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write(root, rel, text):
    p = os.path.join(root, *rel.split("/"))
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8") as f:
        f.write(text)


class Base(unittest.TestCase):
    def setUp(self):
        self.root = tempfile.mkdtemp(prefix="daytest_")
        r = self.root
        write(r, "TSST/core/portfolio.yaml", PORTFOLIO)
        write(r, "TSST/brands/acme/projects/alpha/project.md", PROJECT_MD)
        write(r, "TSST/brands/acme/status.md", STATUS_MD)
        write(r, "TSST/brands/_template/status.md", "## Next action\n<template should be skipped>\n")
        write(r, "TSST/brands/acme/memory/source.md", "## Next\n- MUST NEVER BE READ\n")
        write(r, "TSST/bus/tasks/T-1.yaml", BUS)
        write(r, "TSST/bus/tasks/T-2.yaml", BUS_READY)
        write(r, "TSST/skills/index.yaml", INDEX)

    def tearDown(self):
        shutil.rmtree(self.root, ignore_errors=True)

    def run_day(self, *argv, today=TODAY):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            rc = day.main(["--root", self.root, "--today", today] + list(argv))
        return rc, out.getvalue(), err.getvalue()

    def board(self):
        with open(os.path.join(self.root, "TSST/daily/board.json"), encoding="utf-8") as f:
            return json.load(f)

    def inbox(self):
        p = os.path.join(self.root, "TSST/daily/inbox.md")
        return slurp(p) if os.path.isfile(p) else ""

    def fill_all(self, skills="TSST-DEV-SK-011"):
        """Plan every row so the board can be locked."""
        for r in self.board()["rows"]:
            if r["status"] == "todo":
                self.run_day("set", str(r["id"]), "team=build", "agent=tsst-dev", "tier=CODE",
                             "executor=claude", "skills=" + skills, "done_when=done")


class TestCollect(Base):
    def test_collect_builds_draft(self):
        rc, out, _ = self.run_day("collect")
        self.assertEqual(rc, 0, out)
        b = self.board()
        self.assertEqual((b["date"], b["status"]), (TODAY, "DRAFT"))
        tasks = [r["task"] for r in b["rows"]]
        self.assertEqual(tasks.count("ship the alpha demo"), 1, "dedupe per brand/project")
        self.assertIn("write the brief", tasks)
        self.assertIn("acme brand level next", tasks)
        self.assertIn("Call the printer and confirm the paper stock.", tasks)
        self.assertTrue(any(t.startswith("Lead: review/close T-1") for t in tasks))
        self.assertTrue(any("T-2" in t and "info only" in r["note"] for r, t in zip(b["rows"], tasks)))
        self.assertFalse(any("MUST NEVER" in t or "template" in t for t in tasks))
        lead = [r for r in b["rows"] if "T-1" in r["task"]][0]
        self.assertEqual((lead["team"], lead["agent"], lead["executor"]), ("lead", "lead", "claude"))
        self.assertIn("acme", out)
        md = slurp(os.path.join(self.root, "TSST/daily/today.md"))
        self.assertTrue(md.startswith("<!-- generated by day.py — do not edit -->"))
        self.assertIn("مسودة", md)
        self.assertIn("third item \\| with a pipe", md)

    def test_collect_takes_inbox_and_clears_it(self):
        self.run_day("park", "call the vendor", "--brand", "acme")
        self.assertIn("(acme) call the vendor", self.inbox())
        self.run_day("collect")
        self.assertTrue(any(r["source"] == "inbox" and r["task"] == "call the vendor"
                            for r in self.board()["rows"]))
        self.assertNotIn("call the vendor", self.inbox())

    def test_collect_refuses_existing_draft_without_force(self):
        self.run_day("collect")
        rc, _, err = self.run_day("collect")
        self.assertEqual(rc, 1)
        self.assertIn("--force", err)
        self.assertEqual(self.run_day("collect", "--force")[0], 0)

    def test_collect_refuses_when_previous_day_not_closed(self):
        self.run_day("collect", today="2026-10-08")
        rc, _, err = self.run_day("collect", today=TODAY)
        self.assertEqual(rc, 1)
        self.assertIn("run close first", err)

    def test_collect_ok_after_previous_day_closed(self):
        self.run_day("collect", today="2026-10-08")
        self.fill_all()
        self.assertEqual(self.run_day("lock", today="2026-10-08")[0], 0)
        self.assertEqual(self.run_day("close", today="2026-10-08")[0], 0)
        rc, _, _ = self.run_day("collect", today=TODAY)
        self.assertEqual(rc, 0)
        self.assertEqual(self.board()["date"], TODAY)

    def test_collect_refuses_locked_today(self):
        self.run_day("collect")
        self.fill_all()
        self.run_day("lock")
        rc, _, err = self.run_day("collect", "--force")
        self.assertEqual(rc, 1)
        self.assertIn("LOCKED", err)


class TestLock(Base):
    def setUp(self):
        super().setUp()
        self.run_day("collect")

    def test_lock_refuses_missing_fields_and_lists_all(self):
        rc, _, err = self.run_day("lock")
        self.assertEqual(rc, 1)
        self.assertIn("executor is empty", err)
        self.assertIn("done_when is empty", err)
        self.assertEqual(self.board()["status"], "DRAFT")

    def test_lock_refuses_unknown_skill(self):
        self.fill_all(skills="TSST-DEV-SK-999")
        rc, _, err = self.run_day("lock")
        self.assertEqual(rc, 1)
        self.assertIn("unknown skill id 'TSST-DEV-SK-999'", err)

    def test_lock_refuses_too_many_skills(self):
        self.fill_all(skills="TSST-DEV-SK-011,TSST-LEAD-SK-001,TSST-DEV-SK-011,TSST-DEV-SK-011")
        rc, _, err = self.run_day("lock")
        self.assertEqual(rc, 1)
        self.assertIn("1-3 ids", err)

    def test_lock_ok(self):
        self.fill_all()
        rc, out, err = self.run_day("lock")
        self.assertEqual(rc, 0, err)
        b = self.board()
        self.assertEqual(b["status"], "LOCKED")
        self.assertTrue(b["locked_at"])

    def test_ahmed_row_needs_only_task_executor_done_when(self):
        for r in self.board()["rows"]:
            self.run_day("set", str(r["id"]), "executor=ahmed", "done_when=ok")
        self.assertEqual(self.run_day("lock")[0], 0)

    def test_dropped_rows_are_not_validated(self):
        n = len(self.board()["rows"])
        self.fill_all()
        self.run_day("set", "1", "executor=", "status=todo")  # break row 1
        self.assertEqual(self.run_day("lock")[0], 1)
        self.assertEqual(self.run_day("drop", "1")[0], 0)
        self.assertEqual(self.run_day("lock")[0], 0)
        self.assertEqual(len(self.board()["rows"]), n)

    def test_set_on_locked_limits_fields(self):
        self.fill_all()
        self.run_day("lock")
        rc, _, err = self.run_day("set", "1", "executor=ahmed")
        self.assertEqual(rc, 1)
        self.assertIn("LOCKED", err)
        self.assertEqual(self.run_day("set", "1", "status=doing", "note=started")[0], 0)
        self.assertEqual(self.board()["rows"][0]["status"], "doing")
        self.assertEqual(self.run_day("set", "1", "executor=ahmed", "--owner-ok")[0], 0)


class TestAddParkClose(Base):
    def setUp(self):
        super().setUp()
        self.run_day("collect")
        self.fill_all()
        self.run_day("lock")

    def test_add_on_locked_without_owner_ok_refused(self):
        rc, _, err = self.run_day("add", "new thing", "executor=ahmed", "done_when=x")
        self.assertEqual(rc, 1)
        self.assertIn("park", err)
        rc, _, _ = self.run_day("add", "new thing", "executor=ahmed", "done_when=x", "--swap", "1")
        self.assertEqual(rc, 1, "--swap alone (no --owner-ok) is not enough")
        rc, _, _ = self.run_day("add", "new thing", "executor=ahmed", "done_when=x", "--owner-ok")
        self.assertEqual(rc, 1, "--owner-ok alone (no --swap) is not enough")

    def test_add_owner_ok_swap_moves_swapped_row_to_inbox(self):
        before = len(self.board()["rows"])
        victim = self.board()["rows"][0]
        rc, out, err = self.run_day("add", "urgent client call", "executor=ahmed", "done_when=called",
                                    "brand=acme", "--owner-ok", "--swap", "1")
        self.assertEqual(rc, 0, err)
        b = self.board()
        self.assertEqual(len(b["rows"]), before + 1)
        self.assertEqual(b["rows"][0]["status"], "swapped")
        new = b["rows"][-1]
        self.assertTrue(new["added_midday"])
        self.assertEqual(new["status"], "todo")
        self.assertIn(victim["task"] + " (swapped out %s)" % TODAY, self.inbox())

    def test_add_swap_refuses_invalid_new_row(self):
        rc, _, err = self.run_day("add", "incomplete", "--owner-ok", "--swap", "1")
        self.assertEqual(rc, 1)
        self.assertIn("lock validation", err)
        self.assertEqual(self.board()["rows"][0]["status"], "todo", "nothing swapped on refusal")

    def test_add_swap_refuses_finished_row(self):
        self.run_day("set", "1", "status=done")
        rc, _, err = self.run_day("add", "x", "executor=ahmed", "done_when=y", "--owner-ok", "--swap", "1")
        self.assertEqual(rc, 1)
        self.assertIn("only todo/doing/blocked", err)

    def test_park_appends_even_when_locked(self):
        self.assertEqual(self.run_day("park", "idea for tomorrow", "--brand", "vill")[0], 0)
        self.assertEqual(self.run_day("park", "second idea")[0], 0)
        lines = [l for l in self.inbox().splitlines() if l.startswith("- [")]
        self.assertEqual(len(lines), 2)
        self.assertRegex(lines[0], r"^- \[\d{4}-\d{2}-\d{2} \d{2}:\d{2}\] \(vill\) idea for tomorrow$")
        self.assertIn("(general) second idea", lines[1])

    def test_close_carries_unfinished_and_writes_log(self):
        rows = self.board()["rows"]
        self.run_day("set", "1", "status=done")
        self.run_day("set", "2", "status=blocked", "note=waiting on owner")
        rc, out, _ = self.run_day("close")
        self.assertEqual(rc, 0)
        self.assertIn("project checkpoint", out)
        b = self.board()
        self.assertEqual(b["status"], "CLOSED")
        carried = json.loads(slurp(os.path.join(self.root, "TSST/daily/carry.json")))["rows"]
        self.assertEqual([c["task"] for c in carried], [r["task"] for r in rows[1:]],
                         "done row not carried; the rest keep their plan")
        self.assertNotIn("carried from", self.inbox(), "planned rows never go to inbox.md as text")
        log = slurp(os.path.join(self.root, "TSST/daily/log/%s.md" % TODAY))
        self.assertLessEqual(len(log.splitlines()), 30)
        self.assertIn("## Done", log)
        self.assertIn("## Blocked", log)
        md = slurp(os.path.join(self.root, "TSST/daily/today.md"))
        self.assertIn("اتقفل اليوم", md)

    def test_close_is_idempotent(self):
        self.run_day("close")
        first = slurp(os.path.join(self.root, "TSST/daily/carry.json"))
        # simulate a crash after the carry write but before the board write
        b = self.board()
        b["status"] = "LOCKED"
        for r in b["rows"]:
            r["status"] = "todo"
        with open(os.path.join(self.root, "TSST/daily/board.json"), "w", encoding="utf-8") as f:
            json.dump(b, f, ensure_ascii=False)
        self.run_day("close")
        self.assertEqual(slurp(os.path.join(self.root, "TSST/daily/carry.json")), first)

    def test_log_capped_at_30_lines(self):
        b = self.board()
        for i in range(60):
            b["rows"].append(day.new_row(100 + i, "extra task %d" % i, brand="acme", executor="ahmed",
                                         done_when="x"))
        with open(os.path.join(self.root, "TSST/daily/board.json"), "w", encoding="utf-8") as f:
            json.dump(b, f, ensure_ascii=False)
        self.run_day("close")
        log = slurp(os.path.join(self.root, "TSST/daily/log/%s.md" % TODAY))
        self.assertLessEqual(len(log.splitlines()), 30)


