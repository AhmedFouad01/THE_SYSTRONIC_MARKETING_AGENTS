class Refuse(Exception):
    """A deliberate refusal: message goes to stderr, exit code 1."""


# ---------------------------------------------------------------- paths / io
class Ctx:
    def __init__(self, root, today):
        self.root = os.path.abspath(root)
        self.today = today
        self.daily = os.path.join(self.root, "TSST", "daily")
        self.board_path = os.path.join(self.daily, "board.json")
        self.today_md = os.path.join(self.daily, "today.md")
        self.inbox_path = os.path.join(self.daily, "inbox.md")
        self.carry_path = os.path.join(self.daily, "carry.json")
        self.log_dir = os.path.join(self.daily, "log")

    def rel(self, path):
        r = os.path.relpath(path, self.root).replace("\\", "/")
        return r[5:] if r.startswith("TSST/") else r


def atomic_write(path, text):
    """tmp file in the same dir + os.replace; bounded retry for Drive/AV file locks."""
    d = os.path.dirname(path)
    os.makedirs(d, exist_ok=True)
    tmp = os.path.join(d, ".%s.%d.tmp" % (os.path.basename(path), os.getpid()))
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
    last = None
    for attempt in range(4):
        try:
            os.replace(tmp, path)
            return
        except PermissionError as e:  # transient lock on synced drives
            last = e
            time.sleep(0.2 * (attempt + 1))
    try:
        os.remove(tmp)
    except OSError:
        pass
    raise Refuse("could not write %s after retries: %s" % (path, last))


def read_text(path):
    with open(path, "r", encoding="utf-8-sig") as f:
        return f.read()


def read_board(ctx):
    if not os.path.isfile(ctx.board_path):
        return None
    try:
        b = json.loads(read_text(ctx.board_path))
        assert isinstance(b, dict) and isinstance(b.get("rows"), list)
    except Exception as e:
        raise Refuse("board.json is unreadable (%s); fix or remove it by hand, nothing was changed" % e)
    return b


def write_board(ctx, board):
    atomic_write(ctx.board_path, json.dumps(board, ensure_ascii=False, indent=2) + "\n")
    atomic_write(ctx.today_md, render_today(board))


# ---------------------------------------------------------------- inbox
INBOX_RE = re.compile(r"^- \[(?P<ts>[^\]]+)\] \((?P<brand>[^)]*)\) (?P<text>.+?)\s*$")
SUFFIX_RE = re.compile(r"\s*\((?:carried from|swapped out) [^)]*\)\s*$")


def norm(s):
    return re.sub(r"[\W_]+", " ", s.lower(), flags=re.UNICODE).strip()


def inbox_items(ctx):
    if not os.path.isfile(ctx.inbox_path):
        return []
    out = []
    for line in read_text(ctx.inbox_path).splitlines():
        m = INBOX_RE.match(line)
        if m:
            out.append({"ts": m["ts"], "brand": m["brand"], "text": m["text"]})
    return out


def inbox_write(ctx, items):
    lines = [INBOX_HEADER] + ["- [%s] (%s) %s" % (i["ts"], i["brand"], i["text"]) for i in items]
    atomic_write(ctx.inbox_path, "\n".join(lines) + "\n")


def inbox_append(ctx, new_items):
    """Append, skipping items already present (idempotent: safe to re-run after a crash)."""
    items = inbox_items(ctx)
    seen = {(norm(i["brand"]), norm(i["text"])) for i in items}
    added = 0
    for n in new_items:
        key = (norm(n["brand"]), norm(n["text"]))
        if key in seen:
            continue
        seen.add(key)
        items.append(n)
        added += 1
    inbox_write(ctx, items)
    return added


def now_ts():
    return dt.datetime.now().strftime("%Y-%m-%d %H:%M")


def with_suffix(text, label, date):
    return "%s (%s %s)" % (SUFFIX_RE.sub("", text), label, date)


# ---------------------------------------------------------------- carry store
PLAN_FIELDS = ("id", "task", "brand", "project", "team", "agent", "skills", "tier",
               "executor", "after", "done_when", "note")


def has_plan(r):
    return all(str(r.get(k, "")).strip() for k in ("task", "executor", "done_when"))


def carry_read(ctx):
    """Return (date, rows). Missing file = nothing carried; unreadable file is refused, not ignored."""
    if not os.path.isfile(ctx.carry_path):
        return "", []
    try:
        d = json.loads(read_text(ctx.carry_path))
        assert isinstance(d, dict) and isinstance(d.get("rows"), list)
    except Exception as e:
        raise Refuse("carry.json is unreadable (%s); fix it by hand, nothing was changed" % e)
    return d.get("date", ""), d["rows"]


def carry_write(ctx, date, rows):
    atomic_write(ctx.carry_path, json.dumps(
        {"date": date, "rows": [{k: r.get(k, [] if k in ("skills", "after") else "") for k in PLAN_FIELDS}
                                for r in rows]}, ensure_ascii=False, indent=2) + "\n")


# ---------------------------------------------------------------- rows
def new_row(rid, task, **kw):
    row = {"id": rid, "task": task, "brand": "", "project": "", "source": "manual", "team": "",
           "agent": "", "skills": [], "tier": "", "executor": "", "after": [], "done_when": "",
           "status": "todo", "note": "", "added_midday": False}
    row.update(kw)
    return row


def next_id(board):
    return max([r["id"] for r in board["rows"]] + [0]) + 1


def get_row(board, rid):
    for r in board["rows"]:
        if r["id"] == rid:
            return r
    raise Refuse("no row with id %s" % rid)


def load_skill_ids(ctx):
    p = os.path.join(ctx.root, "TSST", "skills", "index.yaml")
    if not os.path.isfile(p):
        return None
    return set(m.upper() for m in re.findall(r"\bid:\s*(TSST-[A-Za-z]+-SK-\d+)", read_text(p)))


def validate_row(row, ctx, board, skill_ids):
    errs = []
    rid = row.get("id", "?")

    def e(msg):
        errs.append("row %s: %s" % (rid, msg))

    if not str(row.get("task", "")).strip():
        e("task is empty")
    if not row.get("executor"):
        e("executor is empty")
    elif row["executor"] not in EXECUTORS:
        e("executor '%s' not in %s" % (row["executor"], "|".join(EXECUTORS)))
    if not str(row.get("done_when", "")).strip():
        e("done_when is empty")
    ids = {r["id"] for r in board["rows"]} | {rid}
    for a in row.get("after", []):
        if a not in ids:
            e("after refers to missing row %s" % a)
        elif a == rid:
            e("row cannot come after itself")
    if row.get("executor") and row["executor"] != "ahmed":
        for f, allowed in (("team", TEAMS), ("agent", AGENTS), ("tier", TIERS)):
            v = row.get(f)
            if not v:
                e("%s is empty (required when executor != ahmed)" % f)
            elif v not in allowed:
                e("%s '%s' not in %s" % (f, v, "|".join(allowed)))
        sk = row.get("skills") or []
        if not 1 <= len(sk) <= 3:
            e("skills must have 1-3 ids (has %d)" % len(sk))
        if skill_ids is None:
            e("TSST/skills/index.yaml not found; cannot verify skill ids")
        else:
            for s in sk:
                if s.upper() not in skill_ids:
                    e("unknown skill id '%s' (not in TSST/skills/index.yaml)" % s)
    return errs


def parse_assignments(pairs):
    out = {}
    for p in pairs:
        if "=" not in p:
            raise Refuse("expected field=value, got '%s'" % p)
        k, v = p.split("=", 1)
        k = k.strip()
        if k == "id" or k not in FIELDS:
            raise Refuse("unknown or read-only field '%s' (fields: %s)" % (k, ", ".join(FIELDS)))
        if k == "skills":
            v = [s.strip().upper() for s in v.split(",") if s.strip()]
        elif k == "after":
            try:
                v = [int(s) for s in v.split(",") if s.strip()]
            except ValueError:
                raise Refuse("after must be comma-separated row ids, got '%s'" % v)
        elif k == "added_midday":
            if v.lower() not in ("true", "false", "1", "0"):
                raise Refuse("added_midday must be true|false")
            v = v.lower() in ("true", "1")
        else:
            v = v.strip()
            if k in ENUMS and v and v not in ENUMS[k]:
                raise Refuse("%s '%s' not in %s" % (k, v, "|".join(ENUMS[k])))
            if k == "status" and not v:
                raise Refuse("status cannot be empty")
        out[k] = v
    return out


# ---------------------------------------------------------------- render
def cell(v):
    if isinstance(v, (list, tuple)):
        v = ", ".join(str(x) for x in v)
    return str(v).replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def render_today(board):
    rows = [r for r in board["rows"] if r["status"] != "dropped"]
    team_rows = sum(1 for r in rows if r["executor"] and r["executor"] != "ahmed")
    ahmed_rows = sum(1 for r in rows if r["executor"] == "ahmed")
    unset = sum(1 for r in rows if not r["executor"])
    mid = sum(1 for r in rows if r.get("added_midday"))
    out = [GENERATED, "", "# بورد يوم %s — %s" % (board["date"], AR_BOARD[board["status"]]), ""]
    if board.get("locked_at"):
        out += ["اتقفل الساعة: %s" % board["locked_at"], ""]
    out.append("| " + " | ".join(AR_HEAD) + " |")
    out.append("|" + "|".join(["---"] * len(AR_HEAD)) + "|")
    for r in rows:
        vals = [r["id"], r["task"], r["brand"], r["team"], r["agent"], r["skills"], r["tier"],
                r["executor"], r["after"], r["done_when"],
                AR_ROW.get(r["status"], r["status"]) + (" — " + r["note"] if r["note"] else "")]
        out.append("| " + " | ".join(cell(v) for v in vals) + " |")
    out += ["", "صفوف الفريق: %d | صفوف أحمد: %d | غير محدد: %d | إضافات منتصف اليوم: %d"
            % (team_rows, ahmed_rows, unset, mid)]
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- collect sources
NEXT_HEAD = re.compile(r"^#{1,6}\s+.*(?:\bnext\b|التال)", re.I)
ANY_HEAD = re.compile(r"^#{1,6}\s")
BULLET = re.compile(r"^\s*(?:[-*+]|\d+[.)])\s+(.*\S)\s*$")
INLINE_NUM = re.compile(r"\s+(?=\d+\.\s)")


def clip(s):
    s = re.sub(r"\s+", " ", s).strip()
    return s if len(s) <= MAX_TEXT else s[:MAX_TEXT - 1].rstrip() + "…"


def next_items(text):
    """Items under the first heading matching /next|التالي/i (bullets, else paragraphs)."""
    lines = text.splitlines()
    sec, on = [], False
    for ln in lines:
        if ANY_HEAD.match(ln):
            if on:
                break
            on = bool(NEXT_HEAD.match(ln))
            continue
        if on:
            sec.append(ln)
    bullets, paras, cur = [], [], []
    for ln in sec:
        if not ln.strip() or ln.strip().startswith("<!--"):
            if cur:
                paras.append(" ".join(cur))
                cur = []
            continue
        m = BULLET.match(ln)
        if m:
            if cur:
                paras.append(" ".join(cur))
                cur = []
            if re.match(r"^\s*\d+[.)]\s", ln):  # numbered line; may hold several inline "2. ..." items
                bullets.extend(re.sub(r"^\d+[.)]\s*", "", p) for p in INLINE_NUM.split(ln.strip()) if p)
            else:
                bullets.append(m.group(1))
        elif bullets and ln.startswith((" ", "\t")):
            bullets[-1] += " " + ln.strip()
        else:
            cur.append(ln.strip())
    if cur:
        paras.append(" ".join(cur))
    items = bullets if bullets else paras
    return [clip(i) for i in items if i.strip()][:MAX_ITEMS_PER_FILE]


def parse_portfolio(text):
    """Minimal indentation parser. Returns [(brand, project|'', next_text)]."""
    res = []
    lines = text.splitlines()
    brand = proj = None
    in_brands = in_projects = False
    i = 0

    def ind(s):
        return len(s) - len(s.lstrip(" "))

    def value_at(idx, key_indent, rest):
        rest = re.sub(r"\s{2,}#.*$", "", rest).strip()
        if rest in ("", ">", "|", ">-", "|-"):
            buf, j = [], idx + 1
            while j < len(lines) and (not lines[j].strip() or ind(lines[j]) > key_indent):
                if lines[j].strip():
                    buf.append(lines[j].strip())
                j += 1
            return " ".join(buf)
        return rest.strip("\"'")

    while i < len(lines):
        raw = lines[i]
        i += 1
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        n = ind(raw)
        m = re.match(r"^(\S[^:]*):\s*(.*)$", raw.strip())
        if not m:
            continue
        key, rest = m.group(1).strip(), m.group(2)
        if n == 0:
            in_brands = key == "brands"
            brand = proj = None
            in_projects = False
        elif in_brands and n == 2:
            brand, proj, in_projects = key, None, False
        elif in_brands and brand and n == 4:
            in_projects = key == "projects"
            proj = None
            if key == "next":
                v = value_at(i - 1, 4, rest)
                if v:
                    res.append((brand, "", v))
        elif in_brands and brand and in_projects and n == 6:
            proj = key
        elif in_brands and brand and in_projects and proj and n == 8 and key == "next":
            v = value_at(i - 1, 8, rest)
            if v:
                res.append((brand, proj, v))
    return res


def flat_yaml(text):
    d = {}
    for ln in text.splitlines():
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*?)\s*$", ln)
        if m and m.group(1) not in d:
            d[m.group(1)] = m.group(2).strip("\"'")
    return d


def gather(ctx):
    """Return (candidates, unparsed). candidate = dict(task, brand, project, source, note, row_kw)."""
    cands, unparsed = [], []

    def add(task, brand, project, source, **kw):
        cands.append({"task": task, "brand": brand, "project": project, "source": source, **kw})

    for it in inbox_items(ctx):
        add(it["text"], it["brand"], "", "inbox", inbox_ts=it["ts"])

    pf = os.path.join(ctx.root, "TSST", "core", "portfolio.yaml")
    if os.path.isfile(pf):
        got = parse_portfolio(read_text(pf))
        if not got:
            unparsed.append("core/portfolio.yaml (no next entries parsed)")
        for b, p, t in got:
            add(t, b, p, "core/portfolio.yaml")
    else:
        unparsed.append("core/portfolio.yaml (missing)")

    brands = os.path.join(ctx.root, "TSST", "brands")
    if os.path.isdir(brands):
        for b in sorted(os.listdir(brands)):
            bdir = os.path.join(brands, b)
            if b.startswith("_") or not os.path.isdir(bdir):
                continue
            files = [(os.path.join(bdir, "status.md"), "")]
            pdir = os.path.join(bdir, "projects")
            if os.path.isdir(pdir):
                for p in sorted(os.listdir(pdir)):
                    if p.startswith("_") or not os.path.isdir(os.path.join(pdir, p)):
                        continue
                    files.append((os.path.join(pdir, p, "project.md"), p))
            for f, proj in files:
                if not os.path.isfile(f):
                    continue
                items = next_items(read_text(f))
                if not items:
                    unparsed.append("%s (no Next/التالي section with content)" % ctx.rel(f))
                for t in items:
                    add(t, b, proj, ctx.rel(f))

    bus = os.path.join(ctx.root, "TSST", "bus", "tasks")
    if os.path.isdir(bus):
        for fn in sorted(os.listdir(bus)):
            if not fn.endswith(".yaml"):
                continue
            path = os.path.join(bus, fn)
            d = flat_yaml(read_text(path))
            tid, st = d.get("id") or fn[:-5], d.get("status", "")
            title = d.get("title", "")
            if st in ("done", "blocked", "escalated"):
                add("Lead: review/close %s — %s" % (tid, title) if title else "Lead: review/close %s" % tid,
                    d.get("brand", ""), "", ctx.rel(path), team="lead", agent="lead", executor="claude",
                    note="bus status: %s" % st)
            elif st in ("ready", "claimed"):
                add("Bus task %s (%s, to %s) — %s" % (tid, st, d.get("to", "?"), title),
                    d.get("brand", ""), "", ctx.rel(path), note="info only: bus status %s" % st)
            elif st == "":
                unparsed.append("%s (no status key)" % ctx.rel(path))
    return cands, unparsed


# ---------------------------------------------------------------- commands
def cmd_collect(ctx, args):
    board = read_board(ctx)
    if board:
        if board["date"] < ctx.today and board["status"] != "CLOSED":
            raise Refuse("board of %s is %s, not CLOSED: run close first" % (board["date"], board["status"]))
        if board["date"] > ctx.today:
            raise Refuse("board dated %s is in the future relative to today %s" % (board["date"], ctx.today))
        if board["date"] == ctx.today:
            if board["status"] == "LOCKED":
                raise Refuse("today's board is LOCKED; use park for new requests")
            if board["status"] == "CLOSED":
                raise Refuse("today's board is already CLOSED; use park for tomorrow")
            if not args.force:
                raise Refuse("today's DRAFT already exists; use --force to rebuild "
                             "(manual edits are lost, inbox-sourced rows go back to the inbox)")
            back = [{"ts": r.get("inbox_ts") or now_ts(), "brand": r["brand"], "text": r["task"]}
                    for r in board["rows"] if r["source"] == "inbox" and r["status"] != "dropped"]
            inbox_append(ctx, back)
            if not carry_read(ctx)[1]:  # an intact carry store is the source of truth (crash re-run)
                keep = [r for r in board["rows"]
                        if str(r["source"]).startswith("carried from") and r["status"] != "dropped"]
                if keep:  # original carry date is kept in the row source
                    carry_write(ctx, str(keep[0]["source"])[len("carried from "):], keep)
            print("WARNING: --force rebuilds the draft; manual edits to previous rows are discarded")
    cands, unparsed = gather(ctx)
    rows, seen = [], set()
    cdate, crows = carry_read(ctx)
    idmap = {}
    for cr in crows:  # carried rows first, plan intact
        key = (norm(cr["brand"]), norm(cr["project"]), norm(cr["task"]))
        if key in seen:
            continue
        seen.add(key)
        idmap[cr["id"]] = len(rows) + 1
        kw = {k: cr[k] for k in PLAN_FIELDS if k not in ("id", "task", "after") and k in cr}
        rows.append(new_row(len(rows) + 1, cr["task"], source="carried from %s" % cdate,
                            after=list(cr.get("after", [])), **kw))
    for r in rows:  # remap after-refs; refs to rows that were not carried are dropped
        r["after"] = [idmap[a] for a in r["after"] if a in idmap]
    carried_keys = {(k[0], k[2]) for k in seen}
    for c in cands:
        if c["source"] == "inbox" and (norm(c["brand"]), norm(SUFFIX_RE.sub("", c["task"]))) in carried_keys:
            continue  # e.g. a swapped-out row: already restored with its plan from the carry store
        key = (norm(c["brand"]), norm(c["project"]), norm(c["task"]))
        if key in seen:
            continue
        seen.add(key)
        kw = {k: v for k, v in c.items() if k not in ("task", "inbox_ts")}
        if c.get("inbox_ts"):
            kw["inbox_ts"] = c["inbox_ts"]
        rows.append(new_row(len(rows) + 1, c["task"], **kw))
    nb = {"date": ctx.today, "status": "DRAFT", "locked_at": "", "rows": rows}
    write_board(ctx, nb)  # board first, then clear inbox: a crash in between is recoverable by --force
    if os.path.isfile(ctx.inbox_path):
        inbox_write(ctx, [])
    if crows:
        carry_write(ctx, "", [])  # last: a crash before this line is recovered by `collect --force` without duplicates
    counts = {}
    for r in rows:
        counts[r["brand"] or "(none)"] = counts.get(r["brand"] or "(none)", 0) + 1
    print("DRAFT board %s: %d rows (%d restored from carry)" % (ctx.today, len(rows), len(idmap)))
    for b in sorted(counts):
        print("  %-16s %d" % (b, counts[b]))
    if unparsed:
        print("could not parse / empty sources:")
        for u in unparsed:
            print("  - " + u)
    print("next: Lead plans every row with `set N field=value`, owner OKs, then `lock`.")


def need_board(ctx):
    b = read_board(ctx)
    if not b:
        raise Refuse("no board; owner says ابدأ اليوم -> collect")
    return b


def cmd_set(ctx, args):
    board = need_board(ctx)
    if board["status"] == "CLOSED":
        raise Refuse("board is CLOSED")
    row = get_row(board, args.id)
    changes = parse_assignments(args.assign)
    if not changes:
        raise Refuse("nothing to set")
    if board["status"] == "LOCKED" and not args.owner_ok:
        bad = [k for k in changes if k not in LOCKED_EDITABLE]
        if bad:
            raise Refuse("board is LOCKED: only status/note can change (not %s) without --owner-ok "
                         "(owner's explicit OK in chat). Park new requests instead." % ", ".join(bad))
    row.update(changes)
    write_board(ctx, board)
    print("row %d updated: %s" % (row["id"], ", ".join(changes)))


def cmd_drop(ctx, args):
    board = need_board(ctx)
    if board["status"] != "DRAFT":
        raise Refuse("drop works on a DRAFT board only (board is %s)" % board["status"])
    row = get_row(board, args.id)
    if row["status"] == "dropped":
        raise Refuse("row %d is already dropped" % row["id"])
    row["status"] = "dropped"
    write_board(ctx, board)
    if row["source"] == "inbox":
        inbox_append(ctx, [{"ts": row.get("inbox_ts") or now_ts(), "brand": row["brand"], "text": row["task"]}])
        print("row %d dropped; returned to the inbox" % row["id"])
    else:
        print("row %d dropped" % row["id"])


def cmd_lock(ctx, args):
    board = need_board(ctx)
    if board["status"] != "DRAFT":
        raise Refuse("lock needs a DRAFT board (board is %s)" % board["status"])
    ids = load_skill_ids(ctx)
    errs = []
    todo = [r for r in board["rows"] if r["status"] == "todo"]
    if not todo:
        errs.append("no todo rows to lock")
    for r in todo:
        errs += validate_row(r, ctx, board, ids)
    if errs:
        raise Refuse("lock refused, %d problem(s):\n  - %s" % (len(errs), "\n  - ".join(errs)))
    board["status"] = "LOCKED"
    board["locked_at"] = now_ts()
    write_board(ctx, board)
    print("board %s LOCKED at %s (%d todo rows)" % (board["date"], board["locked_at"], len(todo)))


def cmd_add(ctx, args):
    board = need_board(ctx)
    if board["status"] == "CLOSED":
        raise Refuse("board is CLOSED; use park")
    fields = parse_assignments(args.assign)
    if "task" in fields:
        raise Refuse("pass the task text as the first argument, not task=")
    row = new_row(next_id(board), args.text.strip(), source="manual")
    row.update(fields)
    if not row["task"]:
        raise Refuse("task text is empty")
    if board["status"] == "LOCKED":
        if not (args.owner_ok and args.swap is not None):
            raise Refuse("board is LOCKED: new work is not added. Use `park \"text\"` so it enters "
                         "tomorrow's inbox. Only with the owner's explicit OK use "
                         "`add \"text\" ... --owner-ok --swap <row>`.")
        old = get_row(board, args.swap)
        if old["status"] not in ("todo", "doing", "blocked"):
            raise Refuse("swap row %d is '%s'; only todo/doing/blocked rows can be swapped"
                         % (old["id"], old["status"]))
        row["added_midday"] = True
        row["status"] = "todo"
        errs = validate_row(row, ctx, board, load_skill_ids(ctx))
        if errs:
            raise Refuse("new row failed lock validation:\n  - " + "\n  - ".join(errs))
        old["status"] = "swapped"
        old["note"] = ("swapped by row %d" % row["id"]) + ("; " + old["note"] if old["note"] else "")
        board["rows"].append(row)
        write_board(ctx, board)  # board first; inbox_append is idempotent
        inbox_append(ctx, [{"ts": now_ts(), "brand": old["brand"],
                            "text": with_suffix(old["task"], "swapped out", ctx.today)}])
        print("row %d added mid-day; row %d swapped out to the inbox" % (row["id"], old["id"]))
        return
    if args.swap is not None or args.owner_ok:
        raise Refuse("--swap/--owner-ok only apply to a LOCKED board")
    board["rows"].append(row)
    write_board(ctx, board)
    print("row %d added" % row["id"])


def cmd_park(ctx, args):
    text = args.text.strip()
    if not text:
        raise Refuse("empty text")
    n = inbox_append(ctx, [{"ts": now_ts(), "brand": args.brand, "text": text}])
    print("parked for tomorrow (%s)" % args.brand if n else "already in the inbox, nothing added")


def log_text(board, groups):
    done, carried, blocked, mid, swaps = groups
    head = ["# Day log %s" % board["date"],
            "rows: %d | done %d | carried %d | blocked %d | mid-day adds %d | swaps %d"
            % (len(board["rows"]), len(done), len(carried), len(blocked), len(mid), len(swaps))]
    sections = [("Done", done), ("Carried to tomorrow", carried), ("Blocked", blocked),
                ("Mid-day adds", mid), ("Swapped out", swaps)]

    def build(k):
        out = list(head)
        for title, rs in sections:
            if not rs:
                continue
            out.append("## %s" % title)
            for r in rs[:k]:
                out.append("- #%d (%s) %s" % (r["id"], r["brand"] or "-", clip(r["task"])[:100]))
            if len(rs) > k:
                out.append("- (+%d more)" % (len(rs) - k))
        return out

    for k in (50, 6, 4, 3, 2, 1, 0):
        lines = build(k)
        if len(lines) <= 30:
            return "\n".join(lines) + "\n"
    return "\n".join(lines[:29] + ["(truncated)"]) + "\n"


def cmd_close(ctx, args):
    board = need_board(ctx)
    if board["status"] != "LOCKED":
        raise Refuse("close needs a LOCKED board (board is %s)" % board["status"])
    rows = board["rows"]
    unfinished = [r for r in rows if r["status"] not in FINISHED]
    blocked = [r for r in rows if r["status"] == "blocked"]
    done = [r for r in rows if r["status"] == "done"]
    mid = [r for r in rows if r.get("added_midday")]
    swaps = [r for r in rows if r["status"] == "swapped"]
    groups = (done, unfinished, blocked, mid, swaps)
    atomic_write(os.path.join(ctx.log_dir, "%s.md" % board["date"]), log_text(board, groups))
    planned = [r for r in unfinished if has_plan(r)]
    noplan = [r for r in unfinished if not has_plan(r)]
    # carry.json is overwritten wholesale (idempotent); swapped rows keep their plan too
    carry_write(ctx, board["date"], planned + [r for r in swaps if has_plan(r)])
    inbox_append(ctx, [{"ts": now_ts(), "brand": r["brand"],
                        "text": with_suffix(r["task"], "carried from", board["date"])} for r in noplan])
    for r in unfinished:
        r["status"] = "carried"
    board["status"] = "CLOSED"
    write_board(ctx, board)  # last: re-running close after a crash is safe (carry overwrite + inbox dedupe)
    print("board %s CLOSED: %d done, %d carried (plan kept in carry.json), %d swapped, %d without plan to inbox" % (
        board["date"], len(done), len(planned), len(swaps), len(noplan)))
    print("reminder: update each touched project checkpoint (core rule Must 6)")


def cmd_show(ctx, args):
    board = read_board(ctx)
    if args.render:  # regenerate today.md only; board.json is not touched
        if not board:
            raise Refuse("no board to render")
        atomic_write(ctx.today_md, render_today(board))
        print("today.md re-rendered from board.json (%d rows shown)"
              % sum(1 for r in board["rows"] if r["status"] != "dropped"))
    if not board or board["date"] != ctx.today:
        if board:
            print("last board: %s (%s)" % (board["date"], board["status"]))
        print("no board today -> owner says ابدأ اليوم -> collect")
        return
    rows = [r for r in board["rows"] if r["status"] != "dropped"]
    dropped = len(board["rows"]) - len(rows)
    c = {}
    for r in rows:
        c[r["status"]] = c.get(r["status"], 0) + 1
    print("board %s  %s  rows=%d  %s" % (board["date"], board["status"], len(rows),
                                         " ".join("%s=%d" % (k, c[k]) for k in sorted(c))))
    for r in rows:
        print("%3d [%-7s] %-10s %-9s %-14s %s%s" % (
            r["id"], r["status"], (r["brand"] or "-")[:10], (r["team"] or "-")[:9],
            r["executor"] or "?", clip(r["task"])[:70],
            "  (after %s)" % ",".join(map(str, r["after"])) if r["after"] else ""))
    print("dropped: %d" % dropped)
    inbox = len(inbox_items(ctx))
    if inbox:
        print("inbox: %d parked for tomorrow" % inbox)


def build_parser():
    p = argparse.ArgumentParser(prog="day.py", description="TSST daily board (R17)")
    p.add_argument("--root", default=DEFAULT_ROOT, help="repo root (default: derived from script path)")
    p.add_argument("--today", default=None, help=argparse.SUPPRESS)
    sub = p.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("collect")
    c.add_argument("--force", action="store_true")
    s = sub.add_parser("set")
    s.add_argument("id", type=int)
    s.add_argument("assign", nargs="+", metavar="field=value")
    s.add_argument("--owner-ok", action="store_true")
    d = sub.add_parser("drop")
    d.add_argument("id", type=int)
    sub.add_parser("lock")
    a = sub.add_parser("add")
    a.add_argument("text")
    a.add_argument("assign", nargs="*", metavar="field=value")
    a.add_argument("--owner-ok", action="store_true")
    a.add_argument("--swap", type=int, default=None)
    pk = sub.add_parser("park")
    pk.add_argument("text")
    pk.add_argument("--brand", default="general")
    sub.add_parser("close")
    sh = sub.add_parser("show")
    sh.add_argument("--render", action="store_true", help="regenerate today.md from board.json (no state change)")
    return p


COMMANDS = {"collect": cmd_collect, "set": cmd_set, "drop": cmd_drop, "lock": cmd_lock,
            "add": cmd_add, "park": cmd_park, "close": cmd_close, "show": cmd_show}


def main(argv=None):
    for st in (sys.stdout, sys.stderr):
        try:
            st.reconfigure(encoding="utf-8")
        except Exception:
            pass
    args = build_parser().parse_args(argv)
    today = args.today or dt.date.today().isoformat()
    ctx = Ctx(args.root, today)
    try:
        COMMANDS[args.cmd](ctx, args)
    except Refuse as e:
        print("REFUSED: %s" % e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
