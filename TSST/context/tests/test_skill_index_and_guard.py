#!/usr/bin/env python3
"""Tests for the central skill index, the Agent dispatch guard hook and bus team_skill_errors (TSST-ADR-003).

Run: python TSST/context/tests/test_skill_index_and_guard.py   (stdlib only; regenerates the deterministic
index.yaml, otherwise read-only on the live repo)
"""
import importlib.util
import json
import os
import re
import subprocess
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
BUILD = os.path.join(REPO, "TSST", "skills", "build_index.py")
INDEX = os.path.join(REPO, "TSST", "skills", "index.yaml")
HOOK = os.path.join(REPO, "TSST", "context", "hooks", "agent_dispatch_guard.py")
FAILS = []


def expect(name, cond):
    print(("PASS " if cond else "FAIL ") + name)
    if not cond:
        FAILS.append(name)


def py(*args, stdin=None):
    return subprocess.run([sys.executable, *args], input=stdin, capture_output=True, text=True, cwd=REPO,
                          env={**os.environ, "CLAUDE_PROJECT_DIR": REPO})


def guard(subagent, prompt):
    payload = {"tool_name": "Agent", "tool_input": {"prompt": prompt}}
    if subagent is not None:
        payload["tool_input"]["subagent_type"] = subagent
    r = py(HOOK, stdin=json.dumps(payload))
    return r.returncode, r.stderr


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_index():
    r = py(BUILD)
    expect("build_index runs", r.returncode == 0)
    text = open(INDEX, encoding="utf-8").read()
    expect("header marks generated", text.startswith("# GENERATED by TSST/skills/build_index.py - do not edit by hand"))
    rows = [l for l in text.splitlines() if l.startswith("  - {id: TSST-") and "team:" in l and "path:" in l]
    by = {}
    for l in rows:
        t = re.search(r"team: (\w+)", l).group(1)
        by[t] = by.get(t, 0) + 1
    for team, n in {"core": 22, "lead": 30, "studio": 26, "motion": 4, "build": 16, "marketing": 12}.items():
        expect(f"index team {team} >= {n} (got {by.get(team, 0)})", by.get(team, 0) >= n)
    ids = [re.search(r"id: (\S+?),", l).group(1) for l in rows]
    expect("ids unique and uppercase", len(ids) == len(set(ids)) and all(i == i.upper() for i in ids))
    expect("no .agents/skills entries", ".agents" not in text)
    paths = [json.loads(re.search(r'path: ("[^"]*")', l).group(1)) for l in rows]
    expect("every entry path exists on disk", all(os.path.isdir(os.path.join(REPO, p)) for p in paths))
    backlog = re.findall(r"^  - \{id: (TSST-[A-Z]+-SK-\d{3}), title:", text.split("\nbacklog:")[1], re.M)
    expect(f"backlog lists registered-but-unpackaged ids (got {len(backlog)})",
           len(backlog) >= 11 and "TSST-LENS-SK-007" in backlog)
    expect("--check passes after build", py(BUILD, "--check").returncode == 0)
    original = open(INDEX, "rb").read()
    try:
        with open(INDEX, "ab") as f:
            f.write(b"# tamper\n")
        expect("--check exits 1 when stale", py(BUILD, "--check").returncode == 1)
    finally:
        with open(INDEX, "wb") as f:
            f.write(original)
    expect("--check passes after restore", py(BUILD, "--check").returncode == 0)
    base = os.path.join(REPO, "TSST", "context_os", "skills")
    fm = [os.path.join(base, d, "SKILL.md") for d in os.listdir(base) if d.startswith("TSST-CTX-SK-")]
    expect("all CTX skills have frontmatter", len(fm) >= 22 and all(open(p, encoding="utf-8").read().startswith("---") for p in fm))


def test_guard():
    ok = "TEAM: build\nSKILLS: TSST-DEV-SK-005, TSST-DEV-SK-011\nDo it"
    rc, _ = guard("tsst-dev", ok)
    expect("team agent valid -> allow", rc == 0)
    rc, _ = guard("tsst-dev", "TEAM: build (DEV_AG lane). SKILLS: TSST-DEV-SK-005 (API) TIER: CODE")
    expect("inline TEAM/SKILLS on one line -> allow", rc == 0)
    rc, _ = guard("tsst-dev", "TEAM: build\nSKILLS: TSST-DEV-SK-005, TSST-CTX-SK-008")
    expect("core skill allowed for any team", rc == 0)
    rc, _ = guard("tsst-dev", "TEAM: lead\nSKILLS: TSST-LENS-SK-001")
    expect("TEAM: lead may use any team's skills", rc == 0)
    rc, _ = guard("tsst-lens", "TEAM: marketing\nSKILLS: TSST-LENS-SK-001")
    expect("lens/marketing allow", rc == 0)
    rc, _ = guard("tsst-spark", "TEAM: marketing\nSKILLS: TSST-SPARK-SK-001")
    expect("spark/marketing allow", rc == 0)
    rc, _ = guard("tsst-creative", "TEAM: studio\nSKILLS: TSST-CREATIVE-SK-003")
    expect("creative/studio allow", rc == 0)
    rc, _ = guard("tsst-motion", "TEAM: motion\nSKILLS: TSST-MOTION-SK-001, TSST-MOTION-SK-002")
    expect("motion/motion allow with TSST-MOTION-SK ids", rc == 0)
    rc, err = guard("tsst-motion", "TEAM: studio\nSKILLS: TSST-CREATIVE-SK-003")
    expect("motion agent with TEAM: studio -> deny", rc == 2)
    rc, err = guard("tsst-creative", "TEAM: studio\nSKILLS: TSST-MOTION-SK-001")
    expect("creative cannot use motion skill (moved) -> deny, names skill", rc == 2 and "TSST-MOTION-SK-001" in err)
    rc, err = guard("tsst-motion", "TEAM: motion\nSKILLS: TSST-CREATIVE-SK-015")
    expect("old TSST-CREATIVE-SK-015 id no longer in index -> deny", rc == 2 and "TSST-CREATIVE-SK-015" in err)
    rc, err = guard("tsst-dev", "TEAM: build\nno skills here")
    expect("missing SKILLS -> deny", rc == 2 and "SKILLS" in err)
    rc, err = guard("tsst-dev", "SKILLS: TSST-DEV-SK-005")
    expect("missing TEAM -> deny", rc == 2 and "TEAM" in err)
    rc, err = guard("tsst-dev", "TEAM: build\nSKILLS: TSST-DEV-SK-999")
    expect("unknown skill ID -> deny, names it", rc == 2 and "TSST-DEV-SK-999" in err)
    rc, err = guard("tsst-dev", "TEAM: studio\nSKILLS: TSST-CREATIVE-SK-003")
    expect("agent/team mismatch -> deny", rc == 2)
    rc, err = guard("tsst-dev", "TEAM: build\nSKILLS: TSST-LENS-SK-001")
    expect("skill team mismatch -> deny, names skill", rc == 2 and "TSST-LENS-SK-001" in err)
    for blocked in ("general-purpose", "claude", "Plan", "tsst-execution-worker", "tsst-code-worker", "mystery-agent"):
        rc, err = guard(blocked, ok)
        expect(f"blocked agent {blocked} -> deny with R1 text", rc == 2 and "TSST R1: use a team agent" in err)
    rc, err = guard(None, ok)
    expect("missing subagent_type = general-purpose -> deny", rc == 2)
    rc, _ = guard("Explore", "TEAM: build\nlist files")
    expect("utility with TEAM -> allow", rc == 0)
    rc, _ = guard("tsst-reader", "TEAM: marketing\nread")
    expect("tsst-reader with TEAM -> allow", rc == 0)
    rc, err = guard("tsst-fast-worker", "TEAM: marketing\nread")
    expect("retired tsst-fast-worker -> deny, points to tsst-reader", rc == 2 and "tsst-reader" in err)
    rc, err = guard("Explore", "list files")
    expect("utility without TEAM -> deny", rc == 2)
    for free in ("claude-code-guide", "statusline-setup"):
        rc, _ = guard(free, "anything")
        expect(f"{free} allowed without checks", rc == 0)
    r = py(HOOK, stdin="not json")
    expect("garbage stdin -> fail-open with warning", r.returncode == 0 and "WARNING" in r.stderr)
    g = load(HOOK, "guard")

    def boom():
        raise OSError("index missing")

    try:
        g.decide({"tool_input": {"subagent_type": "tsst-dev", "prompt": ok}}, index_loader=boom)
        expect("index loader error propagates to main (fail-open there)", False)
    except OSError:
        expect("index loader error propagates to main (fail-open there)", True)

    def dep():
        return {"TSST-DEV-SK-005": ("build", "DEPRECATED"), "TSST-DEV-SK-011": ("build", "UNVALIDATED")}

    res = g.decide({"tool_input": {"subagent_type": "tsst-dev", "prompt": ok}}, index_loader=dep)
    expect("DEPRECATED skill -> deny", bool(res) and "DEPRECATED" in res and "TSST-DEV-SK-005" in res)


def test_bus():
    bus = load(os.path.join(REPO, "TSST", "bus", "bus.py"), "tsst_bus")

    def errs(team, skills):
        return bus.team_skill_errors({"id": "T-X", "kind": "work", "team": team, "skills": skills})

    sk_dev = "TSST/DEV/skills/tsst-dev-sk-005-api-integration-engineering"
    expect("bus: path skill ok", errs("build", [sk_dev]) == [])
    expect("bus: ID skill ok", errs("build", ["TSST-DEV-SK-005"]) == [])
    expect("bus: motion team accepts TSST-MOTION-SK ids", errs("motion", ["TSST-MOTION-SK-001"]) == [])
    expect("bus: lowercase id ok", errs("build", ["tsst-dev-sk-005"]) == [])
    expect("bus: path with /SKILL.md ok", errs("build", [sk_dev + "/SKILL.md"]) == [])
    expect("bus: core skill ok for any team", errs("studio", ["TSST-CTX-SK-008"]) == [])
    expect("bus: lead may use other team's skill", errs("lead", ["TSST-LENS-SK-001", sk_dev]) == [])
    e = errs("build", ["TSST-LENS-SK-001"])
    expect("bus: team mismatch refused naming skill", len(e) == 1 and "TSST-LENS-SK-001" in e[0] and "marketing" in e[0])
    e = errs("build", ["TSST-DEV-SK-999"])
    expect("bus: unknown ID refused", len(e) == 1 and "TSST-DEV-SK-999" in e[0])
    e = errs("build", ["TSST/DEV/skills/nope"])
    expect("bus: unknown path refused", len(e) == 1 and "not in" in e[0])
    expect("bus: no skills refused", any("skills required" in x for x in errs("build", [])))
    expect("bus: bad team refused", any("team must be one of" in x for x in errs("wizards", ["TSST-DEV-SK-005"])))
    orig = bus.skill_index
    try:
        idx = orig()
        patched = [dict(s, status="DEPRECATED") if s["id"] == "TSST-DEV-SK-005" else s for s in idx]
        bus.skill_index = lambda: patched
        e = errs("build", ["TSST-DEV-SK-005"])
        expect("bus: DEPRECATED refused", len(e) == 1 and "DEPRECATED" in e[0] and "TSST-DEV-SK-005" in e[0])
        bus.skill_index = lambda: None
        expect("bus: missing index refused with hint", any("index missing" in x for x in errs("build", ["TSST-DEV-SK-005"])))
    finally:
        bus.skill_index = orig


def test_lookup_and_version():
    before = open(INDEX, "rb").read()
    r = py(BUILD, "--team", "build")
    lines = [l for l in r.stdout.splitlines() if l.strip()]
    expect("--team build exits 0 with rows", r.returncode == 0 and len(lines) >= 16)
    expect("--team rows are 'ID | status | trigger' only", all(l.count(" | ") == 2 and l.startswith("TSST-DEV-SK-") for l in lines))
    expect("--team omits path and caps trigger at 100", all("TSST/" not in l.split(" | ", 2)[2] and len(l.split(" | ", 2)[2]) <= 100 for l in lines))
    expect("--team output is a small slice", len(r.stdout) < 4000)
    expect("--team unknown -> exit 1", py(BUILD, "--team", "wizards").returncode == 1)
    r = py(BUILD, "--id", "tsst-dev-sk-011")
    expect("--id prints path + full trigger", r.returncode == 0 and "TSST/DEV/skills/tsst-dev-sk-011-testing-tdd-engineering" in r.stdout
           and "Use when behavior changes need a test strategy, regression protection or meaningful automated tests." in r.stdout)
    expect("--id unknown -> exit 1", py(BUILD, "--id", "TSST-DEV-SK-999").returncode == 1)
    expect("lookup flags never rewrite index.yaml", open(INDEX, "rb").read() == before)
    bld = load(BUILD, "build_index")
    expect("version: frontmatter wins", bld.skill_version({"version": "2.3"}, "Version: 1.0\n") == "2.3")
    expect("version: body line fallback", bld.skill_version({}, "# T\n\nVersion: 1.0  \nx") == "1.0")
    expect("version: default 0.1", bld.skill_version({}, "no version here") == "0.1")
    text = open(INDEX, encoding="utf-8").read()
    expect("LEAD skills carry body Version 1.0 in index",
           re.search(r"id: TSST-LEAD-SK-001,.*version: \"1\.0\"", text) is not None)


def main():
    for t in (test_index, test_lookup_and_version, test_guard, test_bus):
        t()
    print(f"\n{'all skill-index/guard/bus tests passed' if not FAILS else str(len(FAILS)) + ' FAILED'}")
    for f in FAILS:
        print("  " + f)
    return 1 if FAILS else 0


if __name__ == "__main__":
    sys.exit(main())
