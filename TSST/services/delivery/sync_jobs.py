#!/usr/bin/env python3
"""sync_jobs.py - generate the brand jobs index TSST/brands/<id>/JOBS.md from the DELIVERY.json files (R20).

Usage: python TSST/services/delivery/sync_jobs.py <brand-id> | --all
Scans TSST/brands/<id>/projects/**/DELIVERY.json and writes TSST/brands/<id>/JOBS.md (generated - do not edit):
job path, service, title, status, date, client page, internal page, job_check result. Stdlib only.
Run it after every DELIVERY.json change; it refreshes derived status_sync.py comments
in existing project/status/portfolio pointers. Missing pointers or malformed mirrors fail.
Structured sync does not review narrative prose; job_check.py verifies exact source hashes.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
BRANDS = ROOT / "TSST" / "brands"
HEADER = ("<!-- generated by TSST/services/delivery/sync_jobs.py - do not edit; run: python TSST/services/delivery/sync_jobs.py {b} -->\n"
          "# {b} - jobs index (generated, do not edit)\n\n")
COLS = "| Job | Service | Title | Status | Date | Client page | Internal page | job_check |\n|---|---|---|---|---|---|---|---|\n"


def cell(s):
    return str(s or "").replace("|", "/").replace("\n", " ").strip() or "-"


def scan(brand):
    pdir = BRANDS / brand / "projects"
    rows = []
    for mf in sorted(pdir.rglob("DELIVERY.json")):
        rel = mf.parent.relative_to(pdir).as_posix()
        try:
            m = json.loads(mf.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            m = {}
        rows.append({"rel": rel, "dir": mf.parent, "service": m.get("service"), "title": m.get("title") or m.get("job"),
                     "status": m.get("status") or "?", "date": m.get("date")})
    return rows


def check_result(job_dir):
    p = subprocess.run([sys.executable, str(HERE / "job_check.py"), str(job_dir)], capture_output=True, text=True, encoding="utf-8", errors="replace")
    out = p.stdout.splitlines()
    warns = sum(1 for ln in out if ln.startswith("WARN"))
    fails = sum(1 for ln in out if ln.startswith("FAIL"))
    res = "PASS" if p.returncode == 0 else f"FAIL ({fails})"
    return res + (f", {warns} warn" if warns else "")


def render(brand, rows, results):
    out = [HEADER.format(b=brand), COLS]
    for r in rows:
        d = r["dir"]
        cl = f"[DELIVERY.html](projects/{r['rel']}/DELIVERY.html)" if (d / "DELIVERY.html").is_file() else "-"
        it = f"[DELIVERY_INTERNAL.html](projects/{r['rel']}/DELIVERY_INTERNAL.html)" if (d / "DELIVERY_INTERNAL.html").is_file() else "-"
        out.append(f"| `{r['rel']}` | {cell(r['service'])} | {cell(r['title'])} | {cell(r['status'])} | {cell(r['date'])} | {cl} | {it} | {results.get(r['rel'], 'pending')} |\n")
    if not rows:
        out.append("| _no DELIVERY.json found_ |  |  |  |  |  |  |  |\n")
    return "".join(out)


def sync(brand):
    if not (BRANDS / brand / "projects").is_dir():
        print(f"{brand}: no projects folder, skipped")
        return 1
    from build_brand import build_brand
    build_brand(brand)
    rows = scan(brand)
    # Existing detail pages receive navigation on first adoption. Do not fabricate
    # detail pages for new/unbuilt jobs or regenerate already connected pages.
    from build_delivery import build, Chk, leaks
    for row in rows:
        for audience, filename in (("client", "DELIVERY.html"), ("internal", "DELIVERY_INTERNAL.html")):
            detail = row["dir"] / filename
            if detail.is_file() and 'data-brand-link' not in detail.read_text(encoding="utf-8"):
                _, doc = build(str(row["dir"]), audience, write=False)
                check = Chk()
                check.feed(doc)
                check.close()
                if check.err or check.stack or (audience == "client" and leaks(doc)):
                    raise ValueError(f"Cannot connect invalid delivery page: {detail}")
                detail.write_text(doc, encoding="utf-8", newline="\n")
    # Derived mirrors only: DELIVERY.json remains the authoritative status source.
    from status_sync import sync_brand
    try:
        sync_brand(brand, root=ROOT, write=True)
    except (OSError, UnicodeError, ValueError) as exc:
        print(f"{brand}: status mirrors failed: {exc}")
        return 1
    target = BRANDS / brand / "JOBS.md"
    target.write_text(render(brand, rows, {}), encoding="utf-8", newline="\n")  # pass 1: job_check f) needs the listing
    results = {r["rel"]: check_result(r["dir"]) for r in rows}
    target.write_text(render(brand, rows, results), encoding="utf-8", newline="\n")
    print(f"wrote {target.relative_to(ROOT).as_posix()} ({len(rows)} jobs)")
    return 0


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    if sys.argv[1] == "--all":
        brands = sorted(p.name for p in BRANDS.iterdir() if (p / "projects").is_dir() and any((p / "projects").rglob("DELIVERY.json")))
    else:
        brands = [sys.argv[1]]
    return max([sync(b) for b in brands] or [0])


if __name__ == "__main__":
    sys.exit(main())
